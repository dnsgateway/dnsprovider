//go:build ignore

// gen_wrappers writes wrappers_gen.go: one type for each combination of
// the optional interfaces the fake implements only once scripted, so a
// consumer's type assertions see exactly what was scripted. Each
// interface is one entry of options below; run go generate after adding
// one.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"
)

// option is an optional interface the fake implements once scripted.
type option struct {
	// Name names the option in the wrapper types and the opt constant.
	Name string
	// Iface is the dnsprovider interface.
	Iface string
	// Method is the interface's method, delegating to the fake.
	Method string
}

var options = []option{
	{
		Name:   "Tenants",
		Iface:  "TenantLister",
		Method: "Tenants(ctx context.Context) ([]dnsprovider.Tenant, error) { return p.tenantList(ctx) }",
	},
	{
		Name:   "ZoneStatus",
		Iface:  "ZoneStatusReader",
		Method: "ZoneStatus(ctx context.Context, z dnsprovider.Zone) (dnsprovider.ZoneStatus, error) { return p.zoneStatus(ctx, z) }",
	},
	{
		Name:   "Batcher",
		Iface:  "Batcher",
		Method: "ApplyChangeset(ctx context.Context, cs dnsprovider.Changeset) (dnsprovider.ApplyResult, error) { return p.applyChangeset(ctx, cs) }",
	},
	{
		Name:   "ZoneUpdater",
		Iface:  "ZoneUpdater",
		Method: "UpdateZone(ctx context.Context, z dnsprovider.Zone, u dnsprovider.ZoneUpdate) (dnsprovider.ZoneStatus, error) { return p.updateZone(ctx, z, u) }",
	},
}

func main() {
	var b bytes.Buffer

	b.WriteString(`// Code generated by gen_wrappers.go; DO NOT EDIT.

package providertest

import (
	"context"

	"github.com/dnsgateway/dnsprovider"
)

// opts is a set of the optional interfaces the fake implements once
// scripted.
type opts uint

// The optional interfaces.
const (
`)

	for i, o := range options {
		fmt.Fprintf(&b, "\topt%s opts = 1 << %d\n", o.Name, i)
	}

	b.WriteString(")\n\n")

	var asserts, cases strings.Builder

	for set := 1; set < 1<<len(options); set++ {
		var in []option

		for i, o := range options {
			if set&(1<<i) != 0 {
				in = append(in, o)
			}
		}

		typ := "with"
		var names []string

		for _, o := range in {
			typ += o.Name
			names = append(names, "opt"+o.Name)
		}

		fmt.Fprintf(&b, "// %s is the fake as a %s.\n", typ, joinIfaces(in))
		fmt.Fprintf(&b, "type %s struct {\n\t*Provider\n}\n\n", typ)

		for _, o := range in {
			fmt.Fprintf(&b, "// %s implements dnsprovider.%s.\n", strings.SplitN(o.Method, "(", 2)[0], o.Iface)
			fmt.Fprintf(&b, "func (p %s) %s\n\n", typ, o.Method)
			fmt.Fprintf(&asserts, "\t_ dnsprovider.%s = %s{}\n", o.Iface, typ)
		}

		fmt.Fprintf(&cases, "\tcase %s:\n\t\treturn %s{p}\n", strings.Join(names, " | "), typ)
	}

	fmt.Fprintf(&b, "var (\n%s)\n\n", asserts.String())
	fmt.Fprintf(&b, `// wrap is the fake implementing the optional interfaces in set.
func wrap(p *Provider, set opts) dnsprovider.Provider {
	switch set {
%s	}

	return p
}
`, cases.String())

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("gofmt: %v\n%s", err, b.Bytes())
	}

	if err := os.WriteFile("wrappers_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// joinIfaces names interfaces for a comment: "a, b and c".
func joinIfaces(in []option) string {
	var names []string
	for _, o := range in {
		names = append(names, "dnsprovider."+o.Iface)
	}

	if len(names) == 1 {
		return names[0]
	}

	return strings.Join(names[:len(names)-1], ", ") + " and " + names[len(names)-1]
}
