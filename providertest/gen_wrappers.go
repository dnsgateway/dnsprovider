//go:build ignore

// gen_wrappers writes wrappers_gen.go: one type for each combination of
// the options, sets of optional interfaces the fake implements only once
// scripted, so a consumer's type assertions see what was scripted. Each
// option is one entry of options below; run go generate after adding one.
// Each option doubles the types: an interface that a consumer does not
// branch on by type alone joins an option rather than adding one.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"
)

// option is a set of optional interfaces the fake implements once
// scripted, together.
type option struct {
	// Name names the option in the wrapper types and the opt constant.
	Name string
	// Ifaces are the option's interfaces.
	Ifaces []iface
}

// iface is one dnsprovider interface the fake implements.
type iface struct {
	// Name is the dnsprovider interface.
	Name string
	// Methods are its methods, each delegating to the fake.
	Methods []string
}

// options are each an option: the types are one per combination, so each
// option doubles them. The Zone writes are one option, as a consumer
// offers each by its Factory's Capabilities: the fake implements all
// three once any is scripted, and one not scripted refuses (see
// scope.unscripted).
var options = []option{
	{
		Name: "Tenants",
		Ifaces: []iface{{
			Name:    "TenantLister",
			Methods: []string{"Tenants(ctx context.Context) ([]dnsprovider.Tenant, error) { return p.tenantList(ctx) }"},
		}},
	},
	{
		Name: "ZoneStatus",
		Ifaces: []iface{{
			Name:    "ZoneStatusReader",
			Methods: []string{"ZoneStatus(ctx context.Context, z dnsprovider.Zone) (dnsprovider.ZoneStatus, error) { return p.zoneStatus(ctx, z) }"},
		}},
	},
	{
		Name: "KeyReader",
		Ifaces: []iface{{
			Name:    "KeyReader",
			Methods: []string{"SigningKeys(ctx context.Context, z dnsprovider.Zone) ([]dnsprovider.SigningKey, error) { return p.signingKeys(ctx, z) }"},
		}},
	},
	{
		Name: "DSRegistrar",
		Ifaces: []iface{{
			Name: "DSRegistrar",
			Methods: []string{
				"DelegationSigners(ctx context.Context, z dnsprovider.Zone) ([]dnsprovider.SigningKey, error) { return p.delegationSigners(ctx, z) }",
				"SetDelegationSigners(ctx context.Context, z dnsprovider.Zone, keys []dnsprovider.SigningKey) error { return p.setDelegationSigners(ctx, z, keys) }",
			},
		}},
	},
	{
		Name: "Batcher",
		Ifaces: []iface{{
			Name:    "Batcher",
			Methods: []string{"ApplyChangeset(ctx context.Context, cs dnsprovider.Changeset) (dnsprovider.ApplyResult, error) { return p.applyChangeset(ctx, cs) }"},
		}},
	},
	{
		Name: "ZoneWrites",
		Ifaces: []iface{
			{
				Name: "ZoneUpdater",
				Methods: []string{`UpdateZone(ctx context.Context, z dnsprovider.Zone, u dnsprovider.ZoneUpdate) (dnsprovider.ZoneStatus, error) {
					if err := p.unscripted(dnsprovider.CapZoneUpdater); err != nil {
						return dnsprovider.ZoneStatus{}, err
					}

					return p.updateZone(ctx, z, u)
				}`},
			},
			{
				Name: "ZoneCreator",
				Methods: []string{`CreateZone(ctx context.Context, name string) (dnsprovider.Zone, error) {
					if err := p.unscripted(dnsprovider.CapZoneCreator); err != nil {
						return dnsprovider.Zone{}, err
					}

					return p.createZone(ctx, p.unscoped, name)
				}`},
			},
			{
				Name: "ZoneDeleter",
				Methods: []string{`DeleteZone(ctx context.Context, z dnsprovider.Zone) error {
					if err := p.unscripted(dnsprovider.CapZoneDeleter); err != nil {
						return err
					}

					return p.deleteZone(ctx, z)
				}`},
			},
		},
	},
}

func main() {
	var b bytes.Buffer

	b.WriteString(`// Code generated by gen_wrappers.go; DO NOT EDIT.

package providertest

import (
	"context"

	"github.com/dnsgateway/dnsprovider"
)

// opts is a set of the optional interfaces the fake implements once
// scripted.
type opts uint

// The optional interfaces.
const (
`)

	for i, o := range options {
		fmt.Fprintf(&b, "\topt%s opts = 1 << %d\n", o.Name, i)
	}

	b.WriteString(")\n\n")

	var asserts, cases strings.Builder

	for set := 1; set < 1<<len(options); set++ {
		var in []option

		for i, o := range options {
			if set&(1<<i) != 0 {
				in = append(in, o)
			}
		}

		typ := "with"
		var names []string

		for _, o := range in {
			typ += o.Name
			names = append(names, "opt"+o.Name)
		}

		fmt.Fprintf(&b, "// %s is the fake as a %s.\n", typ, joinIfaces(in))
		fmt.Fprintf(&b, "type %s struct {\n\t*Provider\n\tscope\n}\n\n", typ)

		for _, o := range in {
			for _, f := range o.Ifaces {
				for _, m := range f.Methods {
					fmt.Fprintf(&b, "// %s implements dnsprovider.%s.\n", strings.SplitN(m, "(", 2)[0], f.Name)
					fmt.Fprintf(&b, "func (p %s) %s\n\n", typ, m)
				}

				fmt.Fprintf(&asserts, "\t_ dnsprovider.%s = %s{}\n", f.Name, typ)
			}
		}

		fmt.Fprintf(&cases, "\tcase %s:\n\t\treturn %s{p, sc}\n", strings.Join(names, " | "), typ)
	}

	fmt.Fprintf(&b, "var (\n%s)\n\n", asserts.String())
	fmt.Fprintf(&b, `// wrap is the fake implementing the optional interfaces in set, built
// within scope sc.
func wrap(p *Provider, set opts, sc scope) dnsprovider.Provider {
	switch set {
%s	}

	return p
}
`, cases.String())

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("gofmt: %v\n%s", err, b.Bytes())
	}

	if err := os.WriteFile("wrappers_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// joinIfaces names interfaces for a comment: "a, b and c".
func joinIfaces(in []option) string {
	var names []string
	for _, o := range in {
		for _, f := range o.Ifaces {
			names = append(names, "dnsprovider."+f.Name)
		}
	}

	if len(names) == 1 {
		return names[0]
	}

	return strings.Join(names[:len(names)-1], ", ") + " and " + names[len(names)-1]
}
